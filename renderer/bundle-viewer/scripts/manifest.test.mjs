/** The shared artifact, read by this side and by the Rust writer's test, generated by neither. */
const SHARED = JSON.parse(readFileSync('../tests/data/manifest-key-sets.json', 'utf8')).key_sets;

test('the reader enforces the shared key sets, not a table of its own', () => {
  // **This is the check that makes the two sides actually agree.** Without it, the reader and the
  // writer each had a hand-maintained table and each had a test over its own table — so both suites
  // stayed green while editing one side alone made every real bundle unreadable. Anchoring both to
  // one artifact neither generates is the discipline `style-agreement.json` already uses.
  const normalize = (o) =>
    Object.fromEntries(Object.entries(o).map(([k, v]) => [k, [...v].sort()]));
  assert.deepEqual(
    normalize(MANIFEST_KEY_SETS),
    normalize(SHARED),
    'the reader and renderer/tests/data/manifest-key-sets.json have drifted apart',
  );
});

