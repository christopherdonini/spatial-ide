function formatBlock() {
  return {
    framing: 'arrow-ipc-stream-per-partition',
    compression: 'none',
    dictionaries: 'none',
    geometry_encoding: 'geoarrow.polygon',
    coordinate_layout: 'interleaved-xy',
    partition_target_bytes: 1048576,
    partition_max_rows: 8192,
    partition_boundary_rule: 'cut-before-append',
    max_partitions: 100000,
  };
}

const parse = (m) => parseManifest(JSON.stringify(m));

/** Every plain-object location in the document, as a list of key paths into it. */
function objectPaths(value, path = []) {
  const out = [];
  if (Array.isArray(value)) {
    value.forEach((v, i) => out.push(...objectPaths(v, [...path, i])));
  } else if (value !== null && typeof value === 'object') {
    out.push(path);
    for (const [k, v] of Object.entries(value)) out.push(...objectPaths(v, [...path, k]));
  }
  return out;
}

const at = (root, path) => path.reduce((v, k) => v[k], root);
const label = (path) => (path.length === 0 ? '$' : `$.${path.join('.')}`);

test('the reference manifest parses, or every mutation below would be meaningless', () => {
  const m = parse(validManifest());
  assert.equal(m.bundleVersion, SUPPORTED_BUNDLE_VERSION);
  assert.equal(m.rows, 3);
  assert.equal(m.partitions.length, 1);
  assert.equal(m.partitions[0].rows, 3);
  assert.equal(m.viewerAssets.length, 2);
  assert.deepEqual(m.attributeColumns, ['zone']);
  assert.equal(m.style.path, 'style.json');
  assert.equal(m.style.bytes, null);
  assert.equal(m.boundsBasis, 'computed-over-published-rows');
  assert.equal(m.reproducibilityGrade, 'Snapshot');
});

test('MUTATION SWEEP — removing any single defined field is refused', () => {
  const paths = objectPaths(validManifest());
  let checked = 0;
  for (const objPath of paths) {
    const keys = Object.keys(at(validManifest(), objPath));
    for (const key of keys) {
      const mutated = validManifest();
      delete at(mutated, objPath)[key];
      // **`manifest-schema-invalid` and nothing else.** An earlier version also accepted
      // `manifest-unsupported-version`, which never fired in any of the 152 removals — so it
      // widened what the sweep would pass without widening what it observed.
      assert.throws(
        () => parse(mutated),
        /manifest-schema-invalid/,
        `removing ${label(objPath)}.${key} was tolerated — §5 makes every member required`,
      );
      checked++;
    }
  }
  // A sweep that swept nothing would pass silently, which is the failure mode this whole file is
  // written against.
  assert.ok(checked > 60, `expected a broad sweep, only ${checked} removals were exercised`);
});

test('MUTATION SWEEP — adding any undefined field is refused', () => {
  const paths = objectPaths(validManifest());
  let checked = 0;
  for (const objPath of paths) {
    const mutated = validManifest();
    at(mutated, objPath).something_a_later_version_added = 1;
    assert.throws(
      () => parse(mutated),
      /manifest-schema-invalid/,
      `an unknown key in ${label(objPath)} was tolerated — §9's reservation argument rests on this`,
    );
    checked++;
  }
  assert.ok(checked > 20, `expected a broad sweep, only ${checked} objects were exercised`);
});

test('partition entries carry bytes and rows as mandatory integers', () => {
  for (const [key, bad] of [
    ['bytes', 1.5],
    ['bytes', '10'],
    ['bytes', null],
    ['rows', 2.5],
    ['rows', '3'],
    ['rows', null],
  ]) {
    const m = validManifest();
    m.data.partitions[0][key] = bad;
    assert.throws(
      () => parse(m),
      /manifest-schema-invalid/,
      `a partition ${key} of ${JSON.stringify(bad)} was accepted`,
    );
  }
});

test('a viewer asset may not carry rows, because the format has no meaning for one', () => {
  // §5 says `rows` is *omitted* on a viewer asset, not null. Tolerating it would accept a manifest
  // asserting a row count for a JavaScript file.
  const m = validManifest();
  m.viewer[0].rows = 0;
  assert.throws(() => parse(m), /manifest-schema-invalid/);

  const n = validManifest();
  n.viewer[0].bytes = null;
  assert.throws(() => parse(n), /manifest-schema-invalid/, 'a viewer asset needs a byte count');
});

test('a bundle_version this build does not implement is refused, not read best-effort', () => {
  // Guessing at a future version's meaning is the silent-conversion failure one level up.
  const m = validManifest();
  m.bundle_version = SUPPORTED_BUNDLE_VERSION + 1;
  assert.throws(() => parse(m), /manifest-unsupported-version/);

  // **A v2 manifest is a v1 manifest with members added** — that is what ADR-017 §3's "additive
  // evolution proceeds by incrementing the version" means — so the version gate must run *before*
  // the key check, or the reader reports `manifest-schema-invalid` for a document whose real
  // problem is its version. §14 lists the two as distinct states so a reader is told which it hit.
  // This is the case that fails when the checks are ordered the other way round.
  const v2 = validManifest();
  v2.bundle_version = SUPPORTED_BUNDLE_VERSION + 1;
  v2.something_v2_added = { anything: true };
  assert.throws(
    () => parse(v2),
    /manifest-unsupported-version/,
    'a future manifest was reported as schema-invalid rather than as an unimplemented version',
  );

  for (const bad of ['one', 1.5, null]) {
    const n = validManifest();
    n.bundle_version = bad;
    assert.throws(() => parse(n), /manifest-schema-invalid/, `bundle_version ${JSON.stringify(bad)}`);
  }
});

test('bytes that are not JSON, or not an object, produce the named state', () => {
  assert.throws(() => parseManifest('not json at all'), /manifest-unparseable/);
  assert.throws(() => parseManifest('[]'), /manifest-schema-invalid/);
  assert.throws(() => parseManifest('null'), /manifest-schema-invalid/);
});

test('an asset path that would escape the bundle is refused before it is fetched', () => {
  const bad = ['../../etc/passwd', '/etc/passwd', 'C:/windows/system32', 'data\\part.arrows', ''];
  for (const path of bad) {
    const m = validManifest();
    m.data.partitions[0].path = path;
    assert.throws(() => parse(m), /manifest-schema-invalid/, `partition path ${JSON.stringify(path)}`);

    const n = validManifest();
    n.viewer[0].path = path;
    assert.throws(() => parse(n), /manifest-schema-invalid/, `viewer path ${JSON.stringify(path)}`);

    const o = validManifest();
    o.style.resource.locators[0].at = path;
    assert.throws(() => parse(o), /manifest-schema-invalid/, `style path ${JSON.stringify(path)}`);
  }
});

test('the reserved slots are refused when occupied, which is what reserving them means', () => {
  const withCache = validManifest();
  withCache.derived_caches = [{ kind: 'pmtiles', path: 'cache.pmtiles' }];
  assert.throws(() => parse(withCache), /manifest-schema-invalid/, 'a derived cache was accepted');

  const withQuery = validManifest();
  withQuery.query_surface.available = true;
  assert.throws(() => parse(withQuery), /manifest-schema-invalid/, 'an available query surface was accepted');
});

test('a ResourceRef member that is neither a string nor a named-unknown state is refused', () => {
  // "An unknown member carries its basis" is only a guarantee if a basis-less state is refused.
  const m = validManifest();
  m.source.source_revision = { state: 'none-pinned' };
  assert.throws(() => parse(m), /manifest-schema-invalid/, 'a state with no basis was accepted');

  const n = validManifest();
  n.source.locators = [];
  assert.throws(() => parse(n), /manifest-schema-invalid/, 'docs/11 requires one or more locators');

  const o = validManifest();
  o.style.resource.content_hash = { state: 'not-applicable', basis: 'x' };
  assert.throws(() => parse(o), /manifest-schema-invalid/, 'a style with no hash cannot be verified');
});

test('the license block is checked against the member set its own state implies', () => {
  const operator = validManifest();
  operator.license = {
    state: 'declared-by-operator',
    license: 'CC-BY-4.0',
    attribution: '© Example',
    redistribution: 'permitted',
    by: 'operator',
    // The instant the operator made the declaration — part of the claim, and a semantic input to
    // the manifest. Not build-execution timing, which lives outside the determinism surface.
    at: '2026-08-06T09:00:00Z',
  };
  assert.doesNotThrow(() => parse(operator));

  // …and the same members under `declared-by-source`, which has no claimant, are refused.
  const wrongState = validManifest();
  wrongState.license = { ...operator.license, state: 'declared-by-source' };
  assert.throws(() => parse(wrongState), /manifest-schema-invalid/);

  const unknownState = validManifest();
  unknownState.license = { state: 'probably-fine' };
  assert.throws(() => parse(unknownState), /manifest-schema-invalid/);
});

test('a source-declared license parses, not only an operator-declared one', () => {
  // This shape appeared in the suite **only inside a negative assertion** — so if it drifted in the
  // shared artifact and the reader together, both suites would stay green while a real
  // source-declared bundle was misjudged. It is a reachable writer output
  // (`kernel/src/publish/mod.rs`, when a source's own footer declares terms), now covered from both
  // sides: `kernel/tests/publish.rs` publishes one from a real parquet footer.
  const m = validManifest();
  m.license = {
    state: 'declared-by-source',
    license: 'CC-BY-4.0',
    attribution: '(c) Example Cadastre',
    redistribution: 'permitted',
  };
  const parsed = parse(m);
  assert.equal(parsed.license.state, 'declared-by-source');
  assert.equal(parsed.license.license, 'CC-BY-4.0');

  // An absent attribution is `null`, never omitted — the member is required, the value may be null.
  const noAttribution = validManifest();
  noAttribution.license = { ...m.license, attribution: null };
  assert.doesNotThrow(() => parse(noAttribution));

  const missing = validManifest();
  missing.license = { state: 'declared-by-source', license: 'CC-BY-4.0', redistribution: 'permitted' };
  assert.throws(() => parse(missing), /manifest-schema-invalid/, 'attribution may be null, not absent');
});

test('a source-declared license may name nothing, and only a source-declared one may', () => {
  // **ADR-017 Corrigendum 1.** The three source metadata keys are independent, so a source can
  // declare attribution and/or redistribution and name no license. `null` is that absence — the
  // writer used to substitute `"(unnamed)"`, text no source wrote, in the one member whose contract
  // is verbatim carriage.
  const noName = validManifest();
  noName.license = {
    state: 'declared-by-source',
    license: null,
    attribution: '(c) Example Cadastre',
    redistribution: 'permitted',
  };
  const parsed = parse(noName);
  assert.equal(parsed.license.license, null);

  // Both absences at once — the shape a source declaring only `redistribution` produces.
  const neither = validManifest();
  neither.license = {
    state: 'declared-by-source',
    license: null,
    attribution: null,
    redistribution: 'permitted',
  };
  assert.doesNotThrow(() => parse(neither));

  // **The asymmetry is the schema, not an oversight.** An operator states a license or makes no
  // declaration at all, so a null here would be a manifest claiming somebody declared terms while
  // naming none. A reader that accepted it would make §5's per-state typing decoration.
  const operatorNull = validManifest();
  operatorNull.license = {
    state: 'declared-by-operator',
    license: null,
    attribution: '© Example',
    redistribution: 'permitted',
    by: 'operator',
    at: '2026-08-06T09:00:00Z',
  };
  assert.throws(
    () => parse(operatorNull),
    /manifest-schema-invalid/,
    'an operator-declared license with no name was accepted',
  );

  // `null` is the only admissible non-string. Anything else is still refused, so widening the type
  // did not turn the member into an unchecked one.
  for (const bad of [42, {}, [], true, { state: 'no-license', basis: 'x' }]) {
    const m = validManifest();
    m.license = {
      state: 'declared-by-source',
      license: bad,
      attribution: null,
      redistribution: 'permitted',
    };
    assert.throws(
      () => parse(m),
      /manifest-schema-invalid/,
      `a source license of ${JSON.stringify(bad)} was accepted`,
    );
  }

  // The member is still **required**: `null` is a value, absence is not.
  const absent = validManifest();
  absent.license = {
    state: 'declared-by-source',
    attribution: null,
    redistribution: 'permitted',
  };
  assert.throws(() => parse(absent), /manifest-schema-invalid/, 'license may be null, not absent');
});

test('the operation filter has exactly the two shapes ADR-017 s8 gives it', () => {
  const bbox = validManifest();
  bbox.operation.filter = {
    kind: 'covering-bbox-intersects',
    xmin: 2600000.0,
    ymin: 1200000.0,
    xmax: 2601000.0,
    ymax: 1201000.0,
    bbox_crs: 'EPSG:2056',
  };
  assert.doesNotThrow(() => parse(bbox));

  const wrongKind = validManifest();
  wrongKind.operation.filter = { kind: 'st-intersects' };
  assert.throws(() => parse(wrongKind), /manifest-schema-invalid/, 'an undefined filter kind was accepted');

  const halfBbox = validManifest();
  halfBbox.operation.filter = { kind: 'covering-bbox-intersects', xmin: 1, ymin: 2 };
  assert.throws(() => parse(halfBbox), /manifest-schema-invalid/);
});

test('a bundle with no bounds parses, because a filter can legitimately select nothing', () => {
  const m = validManifest();
  m.bounds = null;
  const parsed = parse(m);
  assert.equal(parsed.bounds, null);
  assert.equal(parsed.boundsBasis, null, 'an absent bounds must not invent a basis');
});
