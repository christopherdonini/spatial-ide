// Reading the manifest — the bundle's contract, and the first thing a viewer trusts.
//
// A manifest arrives from wherever the bundle was served from, so it is untrusted input in the
// `docs/09` sense. These check that it is treated as one.
//
// ## Why the mutation sweep is the important part of this file
//
// ADR-017 §5 makes every member it defines **required**, and §3 makes a conforming reader **refuse
// an unknown key**. Those are guarantees other parts of the format lean on — §9's reservation of
// `derived_caches` and `query_surface` only buys anything if occupying an *unreserved* key would
// have been refused — so a reader looser than the spec quietly turns the spec into a lie.
//
// Hand-writing one negative case per rule tests the cases someone thought of. Instead the sweep
// below walks **every object in a complete manifest**, and for each one removes each field in turn
// and adds a field that does not belong, asserting that all of it is refused. That is **184
// mutations** — 152 removals across 32 objects, plus one addition per object — and it fails the
// moment the reader is more permissive than the document.

import { readFileSync } from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';

import { importModule } from './bundle-for-test.mjs';

const { parseManifest, SUPPORTED_BUNDLE_VERSION, MANIFEST_KEY_SETS } =
  await importModule('src/manifest.ts');

/** The shared artifact, read by this side and by the Rust writer's test, generated by neither. */
const SHARED = JSON.parse(readFileSync('../tests/data/manifest-key-sets.json', 'utf8')).key_sets;

test('the reader enforces the shared key sets, not a table of its own', () => {
  // **This is the check that makes the two sides actually agree.** Without it, the reader and the
  // writer each had a hand-maintained table and each had a test over its own table — so both suites
  // stayed green while editing one side alone made every real bundle unreadable. Anchoring both to
  // one artifact neither generates is the discipline `style-agreement.json` already uses.
  const normalize = (o) =>
    Object.fromEntries(Object.entries(o).map(([k, v]) => [k, [...v].sort()]));
  assert.deepEqual(
    normalize(MANIFEST_KEY_SETS),
    normalize(SHARED),
    'the reader and renderer/tests/data/manifest-key-sets.json have drifted apart',
  );
});

