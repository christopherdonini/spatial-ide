test('a viewer asset may not carry rows, because the format has no meaning for one', () => {
  // §5 says `rows` is *omitted* on a viewer asset, not null. Tolerating it would accept a manifest
  // asserting a row count for a JavaScript file.
  const m = validManifest();
  m.viewer[0].rows = 0;
  assert.throws(() => parse(m), /manifest-schema-invalid/);

  const n = validManifest();
  n.viewer[0].bytes = null;
  assert.throws(() => parse(n), /manifest-schema-invalid/, 'a viewer asset needs a byte count');
});

test('a bundle_version this build does not implement is refused, not read best-effort', () => {
  // Guessing at a future version's meaning is the silent-conversion failure one level up.
  const m = validManifest();
  m.bundle_version = SUPPORTED_BUNDLE_VERSION + 1;
  assert.throws(() => parse(m), /manifest-unsupported-version/);

  // **A v2 manifest is a v1 manifest with members added** — that is what ADR-017 §3's "additive
  // evolution proceeds by incrementing the version" means — so the version gate must run *before*
  // the key check, or the reader reports `manifest-schema-invalid` for a document whose real
  // problem is its version. §14 lists the two as distinct states so a reader is told which it hit.
  // This is the case that fails when the checks are ordered the other way round.
  const v2 = validManifest();
  v2.bundle_version = SUPPORTED_BUNDLE_VERSION + 1;
  v2.something_v2_added = { anything: true };
  assert.throws(
    () => parse(v2),
    /manifest-unsupported-version/,
    'a future manifest was reported as schema-invalid rather than as an unimplemented version',
  );

  for (const bad of ['one', 1.5, null]) {
    const n = validManifest();
    n.bundle_version = bad;
    assert.throws(() => parse(n), /manifest-schema-invalid/, `bundle_version ${JSON.stringify(bad)}`);
  }
});

test('bytes that are not JSON, or not an object, produce the named state', () => {
  assert.throws(() => parseManifest('not json at all'), /manifest-unparseable/);
  assert.throws(() => parseManifest('[]'), /manifest-schema-invalid/);
  assert.throws(() => parseManifest('null'), /manifest-schema-invalid/);
});

