// Reading the manifest — the bundle's contract, and the first thing a viewer trusts.
//
// A manifest arrives from wherever the bundle was served from, so it is untrusted input in the
// `docs/09` sense. These check that it is treated as one.
//
// ## Why the mutation sweep is the important part of this file
//
// ADR-017 §5 makes every member it defines **required**, and §3 makes a conforming reader **refuse
// an unknown key**. Those are guarantees other parts of the format lean on — §9's reservation of
// `derived_caches` and `query_surface` only buys anything if occupying an *unreserved* key would
// have been refused — so a reader looser than the spec quietly turns the spec into a lie.
//
// Hand-writing one negative case per rule tests the cases someone thought of. Instead the sweep
// below walks **every object in a complete manifest**, and for each one removes each field in turn
// and adds a field that does not belong, asserting that all of it is refused. That is **184
// mutations** — 152 removals across 32 objects, plus one addition per object — and it fails the
// moment the reader is more permissive than the document.

