test('a bundle with no bounds parses, because a filter can legitimately select nothing', () => {
  const m = validManifest();
  m.bounds = null;
  const parsed = parse(m);
  assert.equal(parsed.bounds, null);
  assert.equal(parsed.boundsBasis, null, 'an absent bounds must not invent a basis');
});

// ---------------------------------------------------------------------------------------------
// `viewer_license` — the terms of the CODE, as distinct from `license`, the terms of the DATA.
// ADR-017 Corrigendum 3, discharging ADR-009 item 7.
// ---------------------------------------------------------------------------------------------

test('viewer_license.notice_path must name an entry in viewer[]', () => {
  // **The mutation sweeps above cannot reach this.** They add and remove *keys*; this is
  // referential integrity between two members — the one class `manifest-key-sets.json` cannot
  // express and neither sweep walks. Without this test a manifest whose notice points at nothing
  // would pass every other check in this file.
  const m = validManifest();
  m.viewer_license.notice_path = 'viewer/NOT-THERE.txt';
  assert.throws(
    () => parse(m),
    /manifest-schema-invalid/,
    'a notice_path naming no viewer asset was accepted',
  );

  // The **namespace** half of the same trap: the viewer-relative form is not the bundle-relative
  // one, and only the second is what `viewer[]` carries. A reader that compared loosely would
  // accept a manifest the publisher cannot produce.
  const n = validManifest();
  n.viewer_license.notice_path = 'NOTICE.txt';
  assert.throws(() => parse(n), /manifest-schema-invalid/, 'a viewer-relative notice_path matched');

  // …and removing the notice from viewer[] while leaving the declaration pointing at it is refused
  // from the other direction, which is the case a stripped notice actually produces.
  const o = validManifest();
  o.viewer = o.viewer.filter((a) => a.path !== 'viewer/NOTICE.txt');
  assert.throws(() => parse(o), /manifest-schema-invalid/, 'the notice was removed and tolerated');
});

test('viewer_license members are non-empty and its route kind is closed', () => {
  for (const key of ['program', 'copyright', 'license', 'notice_path']) {
    for (const blank of ['', '   ']) {
      const m = validManifest();
      m.viewer_license[key] = blank;
      assert.throws(
        () => parse(m),
        /manifest-schema-invalid/,
        `a blank ${key} was accepted; a blank is not a notice`,
      );
    }
  }

  for (const blank of ['', '  ']) {
    const m = validManifest();
    m.viewer_license.corresponding_source.at = blank;
    assert.throws(() => parse(m), /manifest-schema-invalid/, 'a blank route destination');
  }

  // Two kinds, closed. A third is a route this reader cannot describe to the person reading it,
  // and describing it wrongly is worse than refusing — §8's `filter` argument exactly.
  for (const kind of ['bundled', 'ftp', '', 'URL']) {
    const m = validManifest();
    m.viewer_license.corresponding_source.kind = kind;
    assert.throws(
      () => parse(m),
      /manifest-schema-invalid/,
      `route kind ${JSON.stringify(kind)} was accepted`,
    );
  }

  // …and `written-offer` is the other legal one, so the check is not simply refusing everything.
  const ok = validManifest();
  ok.viewer_license.corresponding_source.kind = 'written-offer';
  ok.viewer_license.corresponding_source.at = 'Write to the address in the notice file.';
  assert.equal(parse(ok).viewerLicense.correspondingSource.kind, 'written-offer');
});

test('a notice_path that would escape the bundle is refused rather than linked', () => {
  // The notice is rendered as a link, so an unsafe path here is a navigation target, not just a
  // string. Same rule every other asset path gets.
  for (const bad of ['../../etc/passwd', '/etc/passwd', 'C:/evil.txt', 'viewer\\NOTICE.txt']) {
    const m = validManifest();
    m.viewer_license.notice_path = bad;
    m.viewer.push({ path: bad, bytes: 1, content_hash: 'sha256:9999' });
    assert.throws(() => parse(m), /manifest-schema-invalid/, `${bad} was accepted`);
  }
});

test('viewerLicenseSummary states the program, its license, the notice and the route', () => {
  // §14 as Corrigendum 3 amends it makes displaying this normative: a bundle that showed the
  // *data*'s license while silent about the license of the *code the recipient is running* is the
  // thing ADR-009 item 7 exists to prevent. Asserted on the pure function, so what a recipient is
  // actually told is tested without a DOM.
  const m = parse(validManifest());
  const lines = viewerLicenseSummary(m.viewerLicense);
  const joined = lines.map((l) => l.text).join('\n');
  assert.match(joined, /Spatial IDE bundle viewer/);
  assert.match(joined, /AGPL-3\.0-or-later/);
  assert.match(joined, /Copyright \(C\) 2026/);
  assert.match(joined, /viewer\/NOTICE\.txt/);
  assert.match(joined, /https:\/\/example\.invalid\/spatial-ide/);

  // A written offer is labelled as one. A recipient must be able to tell "follow this link" from
  // "write to this address", and the two would otherwise render identically.
  const offer = validManifest();
  offer.viewer_license.corresponding_source = {
    kind: 'written-offer',
    at: 'Write to the address in the notice file, valid three years.',
    note: 'a route recorded, not a guarantee',
  };
  const offerLines = viewerLicenseSummary(parse(offer).viewerLicense);
  assert.match(offerLines.map((l) => l.text).join('\n'), /written offer/i);

  // **Each line carries its own href**, so the page never re-derives a link by matching rendered
  // text. The first version did exactly that, keyed on the whole sentence — rewording a line would
  // have silently turned its link back into plain text with nothing failing, which is the wrong
  // failure mode for the one route a recipient has to the source.
  const [program, copyright, notices, route] = lines;
  assert.equal(program.href, undefined, 'the program line is prose');
  assert.equal(copyright.href, undefined, 'the copyright line is prose');
  // Bundle-relative, not resolved: only the page knows where the bundle root is.
  assert.equal(notices.href, 'viewer/NOTICE.txt', 'the notice line links to the notice');
  assert.equal(route.href, 'https://example.invalid/spatial-ide', 'a url route is followable');
  // A written offer has no destination, and inventing one would be inventing a fact.
  assert.equal(offerLines[3].href, undefined, 'a written offer was linkified');
});

test('a url route with a dangerous or unfollowable scheme is refused by the reader', () => {
  // **The writer refusing these does not protect this reader.** A manifest arrives from wherever the
  // bundle was served from; `main.ts` puts this value into an `href`, so a `javascript:` route would
  // be a clickable script in a page holding the viewer's own origin. Same argument `safeRelativePath`
  // already makes for asset paths: writer-side validation does not reach a bundle the writer did not
  // produce.
  for (const bad of [
    'javascript:alert(1)',
    'JavaScript:alert(1)',
    'data:text/html,<script>alert(1)</script>',
    'file:///C:/dev/spatial-ide',
    'ftp://example.invalid/src',
    'example.invalid/src',
    'https://',
    '//example.invalid/src',
  ]) {
    const m = validManifest();
    m.viewer_license.corresponding_source.at = bad;
    assert.throws(
      () => parse(m),
      /manifest-schema-invalid/,
      `a url route of ${JSON.stringify(bad)} was accepted`,
    );
  }

  // Both legal schemes still pass, so the check is not simply refusing every route.
  for (const good of ['http://example.invalid/src', 'https://example.invalid/spatial-ide']) {
    const m = validManifest();
    m.viewer_license.corresponding_source.at = good;
    assert.equal(parse(m).viewerLicense.correspondingSource.at, good);
  }

  // …and a written offer is deliberately NOT scheme-checked: it is prose, there is no scheme, and
  // `main.ts` renders it as text rather than as a link.
  const offer = validManifest();
  offer.viewer_license.corresponding_source = {
    kind: 'written-offer',
    at: 'Write to the address in the notice file; offer valid three years.',
    note: 'a route recorded, not a guarantee',
  };
  assert.doesNotThrow(() => parse(offer));
});

test('an asset path with a URI scheme is refused, not fetched from another origin', () => {
  // **Pre-existing gap, found while wiring the notice link.** The rule was `/^[A-Za-z]:/` — one
  // letter then a colon — which catches `C:/evil` and admits `https://evil.invalid/x`, whose second
  // character is not a colon. Every blessed path goes to `bundleUrl` = `new URL(path, BUNDLE_BASE)`,
  // and `new URL` resolves an absolute URL by *ignoring the base* — so a manifest could make this
  // page `fetch()` from an attacker's origin, and the request is sent before the content hash can
  // reject the bytes. ADR-017 §14 requires every asset path to be bundle-relative; these are not.
  const schemes = [
    'https://evil.invalid/x',
    'http://evil.invalid/x',
    'data:text/html,<script>alert(1)</script>',
    'javascript:alert(1)',
    'file:///C:/dev/spatial-ide',
    'blob:http://x/y',
    'C:/evil.js',
  ];

  // Every path-bearing member, because the guard is only worth having where it is actually applied.
  for (const s of schemes) {
    const p = validManifest();
    p.data.partitions[0].path = s;
    assert.throws(() => parse(p), /manifest-schema-invalid/, `a partition path of ${s} was accepted`);

    const v = validManifest();
    v.viewer[1].path = s;
    assert.throws(() => parse(v), /manifest-schema-invalid/, `a viewer asset path of ${s} was accepted`);

    const st = validManifest();
    st.style.resource.locators[0].at = s;
    assert.throws(() => parse(st), /manifest-schema-invalid/, `a style path of ${s} was accepted`);

    const n = validManifest();
    n.viewer.push({ path: s, bytes: 1, content_hash: 'sha256:9999' });
    n.viewer_license.notice_path = s;
    assert.throws(() => parse(n), /manifest-schema-invalid/, `a notice_path of ${s} was accepted`);
  }

  // A colon *later* in a name is not a scheme; the rule is about how a path begins and must not
  // over-refuse.
  const ok = validManifest();
  ok.data.partitions[0].path = 'data/report-12:30.arrows';
  assert.doesNotThrow(() => parse(ok));
});
