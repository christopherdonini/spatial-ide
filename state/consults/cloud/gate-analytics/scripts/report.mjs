function groupRow(ps) {
  const fp = (g) => {
    const xs = ps.filter((p) => p.firstPass[g]);
    return xs.length ? `${xs.filter((p) => passed(p.firstPass[g].verdict)).length}/${xs.length} (${pct(xs.filter((p) => passed(p.firstPass[g].verdict)).length, xs.length)})` : '–';
  };
  const allFirst = ps.filter((p) => Object.values(p.firstPass).every((x) => passed(x.verdict))).length;
  const sum = (k) => ps.reduce((s, p) => s + p.findings[k], 0);
  const withReports = ps.filter((p) => p.reports > 0);
  const nRep = withReports.reduce((s, p) => s + p.reports, 0);
  const cr = ps.reduce((s, p) => s + p.correctionRounds, 0);
  const rr = ps.reduce((s, p) => s + p.recordCorrectionRounds, 0);
  const days = ps.map((p) => p.daysFormToMerge).filter((x) => x != null);
  const fsum = withReports.reduce((s, p) => s + p.findings.C + p.findings.E + p.findings.D, 0);
  return {
    n: ps.length,
    rev: fp('reviewer'),
    arch: fp('architect'),
    all: `${allFirst}/${ps.length} (${pct(allFirst, ps.length)})`,
    C: sum('C'),
    E: sum('E'),
    Dn: sum('D'),
    blocking: ps.reduce((s, p) => s + p.blocking, 0),
    perReport: nRep ? fmt((fsum) / nRep, 2) : '–',
    reports: nRep,
    corr: `${cr} (${ps.filter((p) => p.correctionRounds > 0).length} pieces)`,
    corrMean: fmt(mean(ps.map((p) => p.correctionRounds)), 2),
    rec: rr,
    days: days.length ? `${fmt(median(days))} (n=${days.length})` : '–',
    days75: days.length ? fmt(quant(days, 0.75)) : '–',
  };
}
