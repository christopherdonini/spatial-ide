function groupTable(keyFn, order) {
  const groups = new Map();
  for (const p of pieces) {
    const k = keyFn(p);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(p);
  }
  const keys = order ? order.filter((k) => groups.has(k)).concat([...groups.keys()].filter((k) => !order.includes(k))) : [...groups.keys()].sort();
  const rows = keys.map((k) => [k, ...groupCells(groupRow(groups.get(k)))]);
  rows.push(['**All**', ...groupCells(groupRow(pieces))]);
  return rows;
}

