//! **An `engine.identity_unusable` refusal names the source the engine checked** (the follow-up to
//! text-id's C1, `text-id-reopen-with-a-recorded-declaration` §2 items 1 to 3): the variant carries
//! `identity_source`, valued by [`IdSource::as_envelope_value`] of the source the engine checked at
//! the site that refused: `file:id` for the file's own `id` column, checked with no declaration, and
//! `mapped:<column>` for a column a declaration named.
//!
//! Every file here is generated by `spatial_engine::fixture`. The refusals that read the column are
//! the scan's, and these tests read no scan counter, so they may share one process.

use std::path::PathBuf;

use spatial_engine::fixture::{
    write_geoparquet, write_hostile_names, FixtureSpec, HostileColumn, IdentityMode,
};
use spatial_engine::identity::{IdSource, IdentityDeclaration};
use spatial_engine::{CancelToken, Dataset, EngineError};

fn write(name: &str, identity: IdentityMode) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../target/fixtures/text-id-reopen-recorded-declaration");
    std::fs::create_dir_all(&dir).expect("fixture dir");
    let path = dir.join(format!("{name}.parquet"));
    let spec = FixtureSpec {
        features: 200,
        avg_vertices: 8,
        identity,
        ..Default::default()
    };
    write_geoparquet(&path, &spec).expect("write fixture");
    path
}

fn declare(column: &str) -> IdentityDeclaration {
    IdentityDeclaration::new(column, "test", "2026-11-27T00:00:00Z")
}

/// The refusal's `column` and `identity_source`, or a panic naming what came instead.
fn refused(result: Result<Dataset, EngineError>, what: &str) -> (String, String) {
    match result {
        Err(EngineError::IdentityUnusable {
            column,
            identity_source,
            ..
        }) => (column, identity_source),
        Ok(_) => panic!("{what}: expected IdentityUnusable, got an open"),
        Err(other) => panic!("{what}: expected IdentityUnusable, got {other:?}"),
    }
}

fn open_declared(path: &std::path::Path, column: &str) -> Result<Dataset, EngineError> {
    Dataset::open_with_declared_identity(path, declare(column), &CancelToken::new())
}

/// **N-R1.** The type refusal and the two refusals before the scan name the source they checked.
/// File A (a text `id`, no integer column): with no declaration, `file:id`; with `id` declared,
/// `mapped:id`; with `nope` declared, `mapped:nope` (the lookup refusal); and a declared name that
/// cannot be addressed, in a file built as `b1_nul_declared_identity_no_scan.rs` builds its own,
/// `mapped:` and that name. Each value equals `IdSource::as_envelope_value` of the source checked.
///
/// Mutation M-RD1: `dataset.rs` passes `&IdSource::File` to `admit_column_type`, whatever the
/// source. Expected failure: this test fails at the `mapped:id` assertion.
#[test]
fn the_type_refusal_says_whether_id_was_declared() {
    let path = write("file-a", IdentityMode::StringIds);

    let (column, source) = refused(Dataset::open(&path), "no declaration");
    assert_eq!(column, "id");
    assert_eq!(source, "file:id");
    assert_eq!(source, IdSource::File.as_envelope_value());

    let mapped = |column: &str| IdSource::Mapped {
        column: column.to_string(),
        by: "test".to_string(),
        at: "2026-11-27T00:00:00Z".to_string(),
    };

    let (column, source) = refused(open_declared(&path, "id"), "`id` declared");
    assert_eq!(column, "id");
    assert_eq!(source, "mapped:id", "the type refusal of a declared `id`");
    assert_eq!(source, mapped("id").as_envelope_value());

    let (column, source) = refused(open_declared(&path, "nope"), "`nope` declared");
    assert_eq!(column, "nope");
    assert_eq!(
        source, "mapped:nope",
        "the lookup refusal of a declared name"
    );
    assert_eq!(source, mapped("nope").as_envelope_value());

    let dir = std::env::temp_dir().join("spatial-engine-identity-refusal-names-its-source");
    std::fs::create_dir_all(&dir).expect("scratch folder");
    let hostile = dir.join("nul-declared-identity.parquet");
    write_hostile_names(
        &hostile,
        "key\0x",
        &[HostileColumn {
            name: "a",
            int: false,
        }],
    );
    let (column, source) = refused(
        open_declared(&hostile, "key\0x"),
        "a name nothing can address",
    );
    assert_eq!(column, "key\0x");
    assert_eq!(
        source, "mapped:key\0x",
        "the not-addressable refusal of a declared name"
    );
    assert_eq!(source, mapped("key\0x").as_envelope_value());
}

/// **N-R2.** The scan refusals name the source they checked. `DuplicateIds` and `NegativeIds`, each
/// with no declaration, `file:id`, and with `id` declared, `mapped:id`.
///
/// Mutation M-RD2: the duplicate arm of `dataset.rs` is valued `IdSource::File.as_envelope_value()`.
/// Expected failure: this test fails at the `mapped:id` assertion of the repeated `id`.
#[test]
fn the_scan_refusals_say_whether_id_was_declared() {
    let duplicate = write("duplicate", IdentityMode::DuplicateIds);
    let (column, source) = refused(Dataset::open(&duplicate), "duplicates, no declaration");
    assert_eq!((column.as_str(), source.as_str()), ("id", "file:id"));
    let (column, source) = refused(open_declared(&duplicate, "id"), "duplicates, `id` declared");
    assert_eq!(
        (column.as_str(), source.as_str()),
        ("id", "mapped:id"),
        "the repeated-value refusal of a declared `id`"
    );

    let negative = write("negative", IdentityMode::NegativeIds);
    let (column, source) = refused(Dataset::open(&negative), "negatives, no declaration");
    assert_eq!((column.as_str(), source.as_str()), ("id", "file:id"));
    let (column, source) = refused(open_declared(&negative, "id"), "negatives, `id` declared");
    assert_eq!(
        (column.as_str(), source.as_str()),
        ("id", "mapped:id"),
        "the negative-value refusal of a declared `id`"
    );
}
