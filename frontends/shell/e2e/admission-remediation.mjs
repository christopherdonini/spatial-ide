async function main() {
  const DEADLINE_MS = Number(process.env.SPATIAL_E2E_DEADLINE_MS ?? 900_000);
  const watchdog = setTimeout(() => {
    console.error(`admission-remediation: SPATIAL_E2E_DEADLINE_MS (default 900000) exceeded -- presumed hung, failing loudly`);
    process.exit(2);
  }, DEADLINE_MS);
  watchdog.unref();

  const missingFixtures = [];
  if (!existsSync(FIXTURE_NO_CRS) || !existsSync(FIXTURE_MISSING_IDENTITY)) {
    missingFixtures.push([`${FIXTURE_NO_CRS} / ${FIXTURE_MISSING_IDENTITY}`, REGEN_MANUAL_WALKTHROUGH]);
  }
  if (!existsSync(FIXTURE_DUPKEY)) missingFixtures.push([FIXTURE_DUPKEY, REGEN_DUPKEY]);
  if (!existsSync(FIXTURE_BOTHNEEDED)) missingFixtures.push([FIXTURE_BOTHNEEDED, REGEN_BOTHNEEDED]);
  if (!existsSync(FIXTURE_SLOW)) missingFixtures.push([FIXTURE_SLOW, REGEN_SLOW]);
  if (missingFixtures.length > 0) {
    for (const [path, cmd] of missingFixtures) {
      console.error(`admission-remediation: fixture(s) not found: ${path}`);
      console.error(`Regenerate with:\n  ${cmd}`);
    }
    process.exitCode = 1;
    return;
  }

  let session;
  try {
    session = await attachOrLaunch();
  } catch (e) {
    console.error(`admission-remediation: could not attach to or launch the app: ${e.message}`);
    process.exitCode = 1;
    return;
  }

  const { browser, page, launched } = session;
  const consoleHandle = attachConsole(page);

  /** @type {Array<{id: string, status: "PASS"|"FAIL"|"SKIPPED-FAST", note: string}>} */
  const results = [];
  const ctx = {};

  async function runStep(id, timeoutMs, fn) {
    const startedAt = Date.now();
    try {
      const note = await withTimeout(fn(), timeoutMs, id);
      const status = typeof note === "string" && note.startsWith("SKIPPED-FAST:") ? "SKIPPED-FAST" : "PASS";
      results.push({ id, status, note });
      console.log(`[${id}] ${status} (${Date.now() - startedAt}ms): ${note}`);
    } catch (e) {
      const note = e?.message ?? String(e);
      results.push({ id, status: "FAIL", note });
      console.error(`[${id}] FAIL (${Date.now() - startedAt}ms): ${note}`);
    }
  }

  try {
    console.log(`admission-remediation: waiting for the app to mount (up to ${MOUNT_READY_TIMEOUT_MS}ms)...`);
    const mountReady = await waitForMountReady(page);
    console.log(`admission-remediation: mount-readiness gate PASSED after ${mountReady.readyAfterMs}ms`);

    // Harness hygiene, matching regression.mjs's own convention: clear any dismissable banner a
    // previous run (or prior interactive use) may have left up.
    await page
      .evaluate(() => {
        document.querySelectorAll(".canvas-refusal button, .error-banner button").forEach((b) => b.click());
      })
      .catch(() => {});

    await runStep("ASSERT'", 60_000, () => stepAssert(page, consoleHandle, ctx));
    await runStep("PASTED'", 60_000, () => stepPasted(page, consoleHandle, ctx));
    await runStep("AXISTRAP'", 30_000, () => stepAxistrap(page, ctx));
    await runStep("NODEF'", 30_000, () => stepNodef(page));
    await runStep("MAP'", 60_000, () => stepMap(page, consoleHandle));
    await runStep("DUPKEY'", 30_000, () => stepDupkey(page));
    await runStep("BOTHNEEDED'", 60_000, () => stepBothNeeded(page, consoleHandle));
    await runStep("CONFLICT'", 30_000, () => stepConflict(page));
    // Generous: the 4,000,000-feature fixture's uniqueness scan plus CDP round trips, well above
    // what any single phase of it should ever need in practice.
    await runStep("CANCELOPEN'", 120_000, () => stepCancelOpen(page));
    await runStep("NOPERSIST'", 30_000, () => stepNopersist(page));
    await runStep("OVERBOUND'", 30_000, () => stepOverbound(page));

    console.log("");
    console.log("== Summary ==");
    const idWidth = Math.max(...results.map((r) => r.id.length), "Step".length);
    const statusWidth = 12;
    console.log(`${"Step".padEnd(idWidth)}  ${"Status".padEnd(statusWidth)}  Note`);
    console.log(`${"-".repeat(idWidth)}  ${"-".repeat(statusWidth)}  ${"-".repeat(40)}`);
    for (const r of results) {
      console.log(`${r.id.padEnd(idWidth)}  ${r.status.padEnd(statusWidth)}  ${r.note}`);
    }

    const anyFail = results.some((r) => r.status === "FAIL");
    process.exitCode = anyFail ? 1 : 0;
  } catch (e) {
    console.error(`admission-remediation: harness failure: ${e.stack ?? e.message}`);
    process.exitCode = 1;
  } finally {
    try {
      mkdirSync(OUT_DIR, { recursive: true });
      const ledgerPath = join(OUT_DIR, `admission-remediation-render-trace-${Date.now()}.json`);
      writeFileSync(
        ledgerPath,
        JSON.stringify({ renderTrace: consoleHandle.renderTrace(), allConsoleEntries: consoleHandle.entries }, null, 2)
      );
      console.log(`Full render-trace ledger: ${ledgerPath}`);
    } catch (e) {
      console.error(`admission-remediation: failed to write the render-trace ledger: ${e.message}`);
    }
    consoleHandle.dispose();
    await browser.close().catch(() => {});
    console.log(
      launched
        ? `This run launched the app; it stays RUNNING on CDP port ${CDP_PORT} for further interactive use.`
        : `Attached to an already-running app on CDP port ${CDP_PORT}; leaving it running.`
    );
    await new Promise((resolve) => process.stdout.write("", resolve));
    process.exit(process.exitCode ?? 0);
  }
}

await main();
