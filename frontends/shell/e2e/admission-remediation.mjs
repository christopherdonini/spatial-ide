function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/** Bounds one step's whole async body -- identical to regression.mjs's/filter-panel.mjs's own helper. */
function withTimeout(promise, ms, stepId) {
  return new Promise((resolve, reject) => {
    let settled = false;
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      reject(new Error(`${stepId}: timed out after ${ms}ms`));
    }, ms);
    Promise.resolve(promise).then(
      (value) => {
        if (settled) return;
        settled = true;
        clearTimeout(timer);
        resolve(value);
      },
      (err) => {
        if (settled) return;
        settled = true;
        clearTimeout(timer);
        reject(err);
      }
    );
  });
}

/** Polls `getValue()` until `predicate(value)` holds or `timeoutMs` elapses -- identical to
 * regression.mjs's/filter-panel.mjs's own helper. A bounded poll, never a timing claim (ADR-018). */
async function waitForCondition(getValue, predicate, timeoutMs, pollMs = 200) {
  const start = Date.now();
  let last;
  while (Date.now() - start < timeoutMs) {
    last = await getValue();
    if (predicate(last)) return { ok: true, last };
    await sleep(pollMs);
  }
  return { ok: false, last };
}

const MOUNT_READY_TIMEOUT_MS = 90_000;

/** Same gate regression.mjs/filter-panel.mjs use, before the first step -- see regression.mjs's own
 * doc comment for the 2026-08-12 fresh-launch race this closes. */
async function waitForMountReady(page, timeoutMs = MOUNT_READY_TIMEOUT_MS) {
  const start = Date.now();
  let lastHeader = null;
  let lastHookPresent = false;
  let lastEvalError = null;

  while (Date.now() - start < timeoutMs) {
    try {
      const info = await page.evaluate(() => ({
        header: document.querySelector(".app-header")?.textContent ?? null,
        hookPresent:
          typeof window.__SPATIAL_E2E__?.openPath === "function" &&
          typeof window.__SPATIAL_E2E__?.crsCatalog === "function",
      }));
      lastHeader = info.header;
      lastHookPresent = info.hookPresent;
      lastEvalError = null;
      if (lastHeader !== null && lastHookPresent) {
        return { readyAfterMs: Date.now() - start };
      }
    } catch (e) {
      lastEvalError = e?.message ?? String(e);
    }
    await sleep(300);
  }

  const missing = [];
  if (lastHeader === null) missing.push(".app-header non-null");
  if (!lastHookPresent) missing.push("window.__SPATIAL_E2E__.openPath/crsCatalog present");
  throw new Error(
    `mount-readiness gate: timed out after ${timeoutMs}ms waiting for ${missing.join(" and ")}. page url=${page.url()}` +
      (lastEvalError ? `, last evaluate error=${lastEvalError}` : "")
  );
}

function fractionOf(summary) {
  return summary.totalPixels > 0 ? summary.nonBackgroundCount / summary.totalPixels : 0;
}

/**
 * `page.evaluate(fn, arg)` (playwright-core) takes exactly ONE argument after the function --
 * calling it with two trailing values (`page.evaluate(fn, a, b)`) is not a variadic call; the second
 * value is silently dropped, and `fn`'s second parameter is `undefined` inside the page. Every
 * plain, single-argument `page.evaluate((p) => openPath(p), path)` call elsewhere in this suite (and
 * in regression.mjs/filter-panel.mjs) is unaffected -- this only bites a call that needs to hand
 * `openPath` BOTH a path AND an options object, which this file is the first sibling to need. Found
 * live (2026-08-18, this piece's own run): every "assert"/"declare" step was silently replaying a
 * PLAIN open (its `opts` argument dropped), reproducing the SAME initial refusal every time --
 * traced to this exact API misunderstanding, not a product defect. Every call site below that needs
 * to pass `opts` goes through this helper, which bundles both values into the single object
 * `page.evaluate` actually accepts.
 */
function callOpenPath(page, path, opts) {
  return page.evaluate(({ p, o }) => window.__SPATIAL_E2E__.openPath(p, o), { p: path, o: opts });
}

