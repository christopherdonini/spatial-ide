/// The three `viewer_license` refusals, each producing **no bundle at all**.
///
/// ADR-009 item 7 says *every* bundle carries the notice and the route. That is a property of the
/// operation only if the operation refuses to produce one otherwise — so each case here asserts the
/// typed error **and** that the destination does not exist, which is the part that makes the
/// guarantee real rather than advisory.
#[test]
fn a_bundle_that_cannot_carry_the_distributed_codes_terms_is_not_produced_at_all() {
    let d = workspace("viewer-license-refusals");
    let ds = pinned(&fixture(&d, 60));
    let v = viewer();

    // 1. A blank member. Every one of the five is checked, because a loop that tested only the
    //    first would leave four fields whose emptiness nothing refuses.
    for (n, blank) in [
        ("program", 0usize),
        ("copyright", 1),
        ("license", 2),
        ("notice_path", 3),
        ("corresponding_source.at", 4),
    ] {
        let dest = d.join(format!("blank-{n}"));
        let mut req = request(&ds, &v, dest.clone());
        match blank {
            0 => req.viewer_license.program = "   ".into(),
            1 => req.viewer_license.copyright = String::new(),
            2 => req.viewer_license.license = "\t".into(),
            3 => req.viewer_license.notice_path = String::new(),
            _ => req.viewer_license.corresponding_source.at = "  ".into(),
        }
        let e = publish(&req, &CancelToken::new(), None).unwrap_err();
        assert!(
            matches!(e, PublishError::ViewerLicenseIncomplete { member } if member == n),
            "a blank `{n}` produced {e:?}"
        );
        assert!(!dest.exists(), "a bundle exists despite a blank `{n}`");
    }

    // 2. A notice path naming no viewer asset. The declaration would point at nothing, and the
    //    bundle would be refused by every conforming reader — so it is refused here instead.
    let dest = d.join("missing-notice");
    let mut req = request(&ds, &v, dest.clone());
    req.viewer_license.notice_path = "NOTICE-THAT-IS-NOT-THERE.txt".into();
    let e = publish(&req, &CancelToken::new(), None).unwrap_err();
    match &e {
        PublishError::ViewerLicenseNoticeMissing { notice_path, bundle_relative, available } => {
            // **Both namespaces are reported**, because confusing them is the mistake this refusal
            // exists to catch and a message naming only one would not tell the operator which.
            assert_eq!(notice_path, "NOTICE-THAT-IS-NOT-THERE.txt");
            assert_eq!(bundle_relative, "viewer/NOTICE-THAT-IS-NOT-THERE.txt");
            assert!(available.iter().any(|p| p == "NOTICE.txt"), "{available:?}");
        }
        other => panic!("a notice path naming nothing produced {other:?}"),
    }
    assert!(!dest.exists(), "a bundle exists despite a notice path naming nothing");

    // 3. A `url` route that no recipient could follow. A `file://` route is both a docs/09
    //    redaction leak and not durable in ADR-009 item 7's sense.
    for bad in ["file:///C:/dev/spatial-ide", "C:\\dev\\spatial-ide", "spatial-ide", "ftp://x/y"] {
        let dest = d.join("bad-route");
        let mut req = request(&ds, &v, dest.clone());
        req.viewer_license.corresponding_source.at = bad.into();
        let e = publish(&req, &CancelToken::new(), None).unwrap_err();
        assert!(
            matches!(e, PublishError::CorrespondingSourceNotDurable { .. }),
            "`{bad}` was admitted as a url route: {e:?}"
        );
        assert!(!dest.exists());
    }

    // …and a `written-offer` is **not** scheme-checked, because there is no scheme to check. The
    // check must not have become "every route must look like a URL".
    let dest = d.join("written-offer");
    let mut req = request(&ds, &v, dest.clone());
    req.viewer_license.corresponding_source = CorrespondingSource {
        kind: CorrespondingSourceKind::WrittenOffer,
        at: "Write to the address in the notice file for a copy of the source, valid three years."
            .into(),
    };
    publish(&req, &CancelToken::new(), None).unwrap();
    let m: serde_json::Value = serde_json::from_slice(&read(&dest, bundle::MANIFEST_PATH)).unwrap();
    assert_eq!(m["viewer_license"]["corresponding_source"]["kind"], "written-offer");
}

/// A source whose own terms forbid redistribution is refused, because a static bundle **is** a
/// redistributed copy (ADR-006 class 3; `docs/09`).
///
/// The refusal existed and was unit-tested against a hand-built `SourceLicense`; this is the first
/// test that reaches it through a **real parquet footer**, which is the path a real source takes.
#[test]
fn a_source_that_forbids_redistribution_is_refused_before_anything_is_written() {
    let d = workspace("license-forbidden");
    let src = d.join("forbidden.parquet");
    write_geoparquet(
        &src,
        &FixtureSpec {
            features: 100,
            attributes: AttributeMode::CategoricalZone,
            license: LicenseMode::ForbidsRedistribution,
            ..Default::default()
        },
    )
    .unwrap();
    let ds = pinned(&src);
    let v = viewer();
    let dest = d.join("bundle");
    match publish(&request(&ds, &v, dest.clone()), &CancelToken::new(), None).unwrap_err() {
        PublishError::LicenseNotCarryable { declared_by, redistribution } => {
            assert_eq!(declared_by, "source");
            assert_eq!(redistribution, "forbidden");
        }
        other => panic!("expected LicenseNotCarryable, got {other}"),
    }
    assert!(!dest.exists(), "a bundle was written for a source that forbids redistribution");
}
