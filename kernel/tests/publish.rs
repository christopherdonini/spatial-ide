fn workspace(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join("spatial-kernel-publish-tests").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn fixture(dir: &Path, features: usize) -> PathBuf {
    let path = dir.join("parcels.parquet");
    write_geoparquet(
        &path,
        &FixtureSpec {
            features,
            attributes: AttributeMode::CategoricalZone,
            crs_mode: CrsMode::DeclaredLv95,
            identity: IdentityMode::NativeUnique,
            ..Default::default()
        },
    )
    .unwrap();
    path
}

fn pinned(path: &Path) -> Dataset {
    let ds = Dataset::open(path).unwrap();
    ds.pin_content(&CancelToken::new()).unwrap();
    ds
}

fn viewer() -> ViewerAssets {
    // Synthetic, deliberately: a Rust test must not need Node to run. The acceptance run points at
    // the real built viewer instead.
    ViewerAssets::new(vec![
        ViewerAsset { path: "index.html".into(), bytes: b"<!doctype html><title>t</title>".to_vec() },
        ViewerAsset { path: "app.js".into(), bytes: b"export const ok = 1;\n".to_vec() },
        // The notice `viewer_license.notice_path` points at. Synthetic like the rest — the *format*
        // requires the declaration to name a hash-listed asset and deliberately cannot check what
        // is inside it (ADR-017 Corrigendum 3), so a stub is the honest fixture. The real notice
        // set is generated by `renderer/bundle-viewer/build.mjs` and reaches the acceptance run.
        ViewerAsset { path: "NOTICE.txt".into(), bytes: b"stub notice\n".to_vec() },
    ])
    .unwrap()
}

/// The `viewer_license` every request needs (ADR-009 item 7; ADR-017 Corrigendum 3).
///
/// `notice_path` is **viewer-relative** here, as `ViewerAsset::path` is; the publisher emits
/// `viewer/NOTICE.txt`. Tests that care about that translation assert it explicitly.
fn viewer_license() -> ViewerLicenseInput {
    ViewerLicenseInput {
        program: "Spatial IDE bundle viewer".into(),
        copyright: "Copyright (C) 2026 Christopher Donini and the Spatial IDE contributors".into(),
        license: "AGPL-3.0-or-later".into(),
        notice_path: "NOTICE.txt".into(),
        corresponding_source: CorrespondingSource {
            kind: CorrespondingSourceKind::Url,
            at: "https://example.invalid/spatial-ide".into(),
        },
    }
}

fn request<'a>(
    ds: &'a Dataset,
    viewer: &'a ViewerAssets,
    destination: PathBuf,
) -> PublishRequest<'a> {
    PublishRequest {
        dataset: ds,
        dataset_name: "parcels",
        query: ViewportQuery::all(),
        attributes: vec!["zone".into()],
        style_source: STYLE,
        viewer,
        viewer_license: viewer_license(),
        license: None,
        destination,
        // Fixed instants: the operation is a pure function of its inputs, and these reach only the
        // sidecar, which no hash covers.
        started_at: "2026-08-06T09:00:00Z".into(),
        // A fixed clock: the sidecar is excluded from every hash, and a test that let a real one in
        // would be asserting determinism against a value designed to differ.
        finished_at: &FIXED_FINISH,
    }
}

/// The clock the tests hand to `publish`. Named so a test that wants a *different* instant can say
/// so, which `the_sidecar_is_what_differs_between_two_publishes_and_it_is_excluded_by_design` does.
fn fixed_finish() -> String {
    "2026-08-06T09:00:01Z".to_string()
}
static FIXED_FINISH: fn() -> String = fixed_finish;

fn later_finish() -> String {
    "2027-01-01T00:00:05Z".to_string()
}
static LATER_FINISH: fn() -> String = later_finish;

fn read(bundle: &Path, rel: &str) -> Vec<u8> {
    std::fs::read(bundle.join(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}"))
}

#[test]
fn a_published_bundle_has_the_declared_layout_and_lists_every_asset_it_contains() {
    let d = workspace("layout");
    let ds = pinned(&fixture(&d, 3_000));
    let v = viewer();
    let dest = d.join("bundle");
    let out = publish(&request(&ds, &v, dest.clone()), &CancelToken::new(), None).unwrap();

    assert!(dest.join(bundle::MANIFEST_PATH).is_file());
    assert!(dest.join(bundle::STYLE_PATH).is_file());
    assert!(dest.join(bundle::BUILD_INFO_PATH).is_file());
    assert!(dest.join("viewer/index.html").is_file());
    assert!(dest.join(bundle::partition_path(0)).is_file());
    assert_eq!(out.rows, 3_000);
    assert!(out.partitions >= 1);
    assert_eq!(out.reproducibility_grade, "Snapshot");

    // Every listed asset exists, is the listed length, and hashes to the listed hash. This is the
    // property the viewer's verification depends on, checked here from the writing side.
    let manifest: serde_json::Value = serde_json::from_slice(&read(&dest, bundle::MANIFEST_PATH)).unwrap();
    let listed: Vec<&serde_json::Value> = manifest["data"]["partitions"]
        .as_array()
        .unwrap()
        .iter()
        .chain(manifest["viewer"].as_array().unwrap())
        .collect();
    assert!(listed.len() >= 3);
    for asset in listed {
        let rel = asset["path"].as_str().unwrap();
        let bytes = read(&dest, rel);
        assert_eq!(bytes.len() as u64, asset["bytes"].as_u64().unwrap(), "{rel} length");
        assert_eq!(
            spatial_renderer::sha256_hex(&bytes),
            asset["content_hash"].as_str().unwrap(),
            "{rel} hash"
        );
    }
    // The style is listed separately, under its own ResourceRef, and hashes too.
    assert_eq!(
        spatial_renderer::sha256_hex(&read(&dest, bundle::STYLE_PATH)),
        manifest["style"]["resource"]["content_hash"].as_str().unwrap()
    );

    // The sidecar is named but NOT hashed and NOT verified — and the manifest says so, so a reader
    // is not left to discover it.
    assert_eq!(manifest["sidecar"]["path"].as_str().unwrap(), bundle::BUILD_INFO_PATH);
    assert_eq!(manifest["sidecar"]["hashed"].as_bool().unwrap(), false);
    assert_eq!(manifest["sidecar"]["verified"].as_bool().unwrap(), false);
}

#[test]
fn publishing_twice_from_identical_inputs_gives_a_byte_identical_manifest() {
    // The acceptance criterion, and the reason the ordering, the fixed partition policy and the
    // canonical number grammar all exist.
    let d = workspace("determinism");
    let src = fixture(&d, 4_000);
    let v = viewer();

    let ds_a = pinned(&src);
    let a = publish(&request(&ds_a, &v, d.join("a")), &CancelToken::new(), None).unwrap();
    // A second *open* as well as a second publish: the manifest must not depend on process state
    // that happens to survive between the two.
    let ds_b = pinned(&src);
    let b = publish(&request(&ds_b, &v, d.join("b")), &CancelToken::new(), None).unwrap();

    let ma = read(&d.join("a"), bundle::MANIFEST_PATH);
    let mb = read(&d.join("b"), bundle::MANIFEST_PATH);
    assert_eq!(ma, mb, "two publishes produced different manifest bytes");
    assert_eq!(a.style_hash, b.style_hash);
    assert_eq!(a.operation_digest, b.operation_digest);
    assert_eq!(a.partitions, b.partitions);

    // …and every partition is byte-identical, which is the thing the manifest's hashes assert.
    for i in 0..a.partitions {
        let rel = bundle::partition_path(i);
        assert_eq!(read(&d.join("a"), &rel), read(&d.join("b"), &rel), "partition {i} differs");
    }
    // The style bytes too.
    assert_eq!(read(&d.join("a"), bundle::STYLE_PATH), read(&d.join("b"), bundle::STYLE_PATH));
}

/// **The operator-declared branch is inside the determinism guarantee, and `license.at` is why.**
///
/// ADR-017 §12 scopes byte-identity to "identical source bytes, style bytes, declared projection,
/// publish parameters and viewer asset bytes" — and §10 places `license.at` among the *parameters*,
/// because it describes the **request** (an operator declared terms at an instant) rather than the
/// **execution**. Both halves of that are asserted here, and both were unasserted before: the
/// shared `request()` helper sets `license: None`, so the determinism test above never reached this
/// branch at all.
///
/// It is not a hypothetical gap. `publish-bundle` passed its own build clock as `license.at`, so
/// every operator-declared publish produced a different manifest — the guarantee was false for the
/// whole branch and no test could see it. The binary now requires `--license-at`.
#[test]
fn two_operator_declared_publishes_agree_byte_for_byte_and_a_different_instant_is_a_different_publish()
{
    let d = workspace("operator-license-determinism");
    let src = fixture(&d, 800);
    let v = viewer();

    let declaration = |at: &str| OperatorLicense {
        license: "CC-BY-4.0".into(),
        attribution: Some("© Example Cadastre".into()),
        redistribution: bundle::Redistribution::Permitted,
        by: "operator".into(),
        at: at.into(),
    };

    let ds_a = pinned(&src);
    let mut a = request(&ds_a, &v, d.join("a"));
    a.license = Some(declaration("2026-08-06T09:00:00Z"));
    publish(&a, &CancelToken::new(), None).unwrap();

    // Same declaration, a second open, and a **later build** — the sidecar's instants differ.
    let ds_b = pinned(&src);
    let mut b = request(&ds_b, &v, d.join("b"));
    b.license = Some(declaration("2026-08-06T09:00:00Z"));
    b.started_at = "2027-01-01T00:00:00Z".into();
    b.finished_at = &LATER_FINISH;
    publish(&b, &CancelToken::new(), None).unwrap();

    assert_eq!(
        read(&d.join("a"), bundle::MANIFEST_PATH),
        read(&d.join("b"), bundle::MANIFEST_PATH),
        "build timing reached the manifest through the operator-declared license branch"
    );
    assert_ne!(
        read(&d.join("a"), bundle::BUILD_INFO_PATH),
        read(&d.join("b"), bundle::BUILD_INFO_PATH),
        "the two builds were not actually distinguishable, so the assertion above proves nothing"
    );

    // …and the other half: a **different declaration instant is a different request**, so it must
    // produce a different manifest. Without this, `license.at` could be silently dropped from the
    // manifest entirely and the assertion above would still pass.
    let ds_c = pinned(&src);
    let mut c = request(&ds_c, &v, d.join("c"));
    c.license = Some(declaration("2026-08-06T17:30:00Z"));
    publish(&c, &CancelToken::new(), None).unwrap();
    assert_ne!(
        read(&d.join("a"), bundle::MANIFEST_PATH),
        read(&d.join("c"), bundle::MANIFEST_PATH),
        "two different operator declarations produced one manifest; `license.at` is not carried"
    );

    let m: serde_json::Value =
        serde_json::from_slice(&read(&d.join("c"), bundle::MANIFEST_PATH)).unwrap();
    assert_eq!(m["license"]["at"], "2026-08-06T17:30:00Z");
}

#[test]
fn the_sidecar_is_what_differs_between_two_publishes_and_it_is_excluded_by_design() {
    // If the wall-clock facts lived in the manifest, the assertion above would be false. This test
    // is the other half of that argument: the values really do differ, and they really are outside
    // every hash.
    let d = workspace("sidecar");
    let src = fixture(&d, 800);
    let v = viewer();

    let ds = pinned(&src);
    let mut req = request(&ds, &v, d.join("a"));
    publish(&req, &CancelToken::new(), None).unwrap();

    req.destination = d.join("b");
    req.started_at = "2027-01-01T00:00:00Z".into();
    req.finished_at = &LATER_FINISH;
    publish(&req, &CancelToken::new(), None).unwrap();

    assert_eq!(
        read(&d.join("a"), bundle::MANIFEST_PATH),
        read(&d.join("b"), bundle::MANIFEST_PATH),
        "a timestamp reached the manifest"
    );
    assert_ne!(
        read(&d.join("a"), bundle::BUILD_INFO_PATH),
        read(&d.join("b"), bundle::BUILD_INFO_PATH),
        "the sidecar did not record the instants it exists to record"
    );
}

#[test]
fn the_redaction_scan_passes_over_every_byte_of_an_emitted_bundle() {
    // docs/09, asserted over the artifact rather than over the intention. The scan reads every file
    // including the partitions and the sidecar.
    let d = workspace("redaction");
    let ds = pinned(&fixture(&d, 2_000));
    let v = viewer();
    let dest = d.join("bundle");
    publish(&request(&ds, &v, dest.clone()), &CancelToken::new(), None).unwrap();

    // **The operator's own declarations are supplied**, so a match inside one is attributed rather
    // than reported as a leak (ADR-017 Corrigendum 3). ADR-009 item 7 makes a copyright notice a
    // required manifest member, and on a single-maintainer machine the login name *is* the name in
    // that notice — the scan sees a username and cannot tell, from bytes, that the operator typed
    // it deliberately. Nothing is suppressed: `redaction.rs` re-classes only a match lying wholly
    // inside a declared occurrence, and its own unit tests pin both halves of that.
    let vl = viewer_license();
    let machine = redaction::MachineIdentifiers {
        declared: vec![vl.copyright.clone(), vl.corresponding_source.at.clone()],
        ..redaction::MachineIdentifiers::from_environment()
    };
    let findings = redaction::scan_directory(&dest, &machine).unwrap();
    // Undeclared findings are the ones that mean something went wrong. Declared ones are listed
    // separately below rather than dropped, so this test cannot pass by explaining everything away.
    let leaked: Vec<_> = findings
        .iter()
        .filter(|f| f.class != redaction::OPERATOR_DECLARED)
        .collect();
    assert!(leaked.is_empty(), "redaction findings in the emitted bundle: {leaked:#?}");

    // …and the attribution is doing real work rather than being dead configuration: on a machine
    // whose username appears in the declared copyright there **is** a re-classed finding, and this
    // asserts the mechanism is exercised when that is so. On a machine where it is not, there is
    // nothing to attribute and nothing to assert — stated rather than left as a flaky expectation.
    if vl.copyright.to_lowercase().contains(
        &machine.usernames.first().cloned().unwrap_or_else(|| "\u{0}".into()).to_lowercase(),
    ) {
        assert!(
            findings.iter().any(|f| f.class == redaction::OPERATOR_DECLARED),
            "the declared copyright contains this machine's username, so the scan should have \
             attributed a match rather than finding nothing: {findings:#?}"
        );
    }

    // The scan is only meaningful if it *can* fire — a grep that finds nothing because it looks for
    // nothing is not evidence. This is the same directory with one planted string.
    std::fs::write(dest.join("planted.txt"), b"opened C:\\dev\\secret.parquet").unwrap();
    let after = redaction::scan_directory(&dest, &machine).unwrap();
    assert!(
        after.iter().any(|f| f.class == "local-filesystem-path"),
        "the scan cannot detect what it claims to"
    );
}

#[test]
fn cancelling_mid_publish_leaves_no_bundle_and_no_staging_directory() {
    let d = workspace("cancel");
    let ds = pinned(&fixture(&d, 30_000));
    let v = viewer();
    let dest = d.join("bundle");

    // Cancel once the first partitions are on disk, so the cancel lands *during* writing rather
    // than before it starts — the case "no partial output" is actually about.
    struct CancelAfter {
        cancel: CancelToken,
        after: usize,
    }
    impl PublishProgress for CancelAfter {
        fn phase(&self, _: PublishPhase) {}
        fn partition_written(&self, index: usize, _: usize, _: u64) {
            if index + 1 >= self.after {
                self.cancel.cancel();
            }
        }
    }

    let cancel = CancelToken::new();
    let obs = CancelAfter { cancel: cancel.clone(), after: 2 };
    let e = publish(&request(&ds, &v, dest.clone()), &cancel, Some(&obs)).unwrap_err();
    assert!(matches!(e, PublishError::Cancelled), "got {e}");

    assert!(!dest.exists(), "a bundle exists under the destination name after a cancel");
    let leftovers: Vec<String> = std::fs::read_dir(&d)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().to_string())
        .filter(|n| n.contains("staging"))
        .collect();
    assert!(leftovers.is_empty(), "staging directories left behind: {leftovers:?}");
}

