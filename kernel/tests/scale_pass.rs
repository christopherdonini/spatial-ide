/// Run the real `publish-bundle`, through the sanctioned approval path.
fn publish_via_cli(
    data: &Path,
    style: &Path,
    viewer: &Path,
    out: &Path,
    audit_log: &Path,
) -> (bool, f64, String) {
    let exe = binary_beside_me("publish-bundle");
    let approve = out.file_name().unwrap().to_string_lossy().to_string();
    let grant_dir = out.parent().unwrap();

    let t = Instant::now();
    let output = std::process::Command::new(exe)
        .env("SPATIAL_IDE_AUDIT_LOG", audit_log)
        .args([
            "--data", data.to_str().unwrap(),
            "--style", style.to_str().unwrap(),
            "--viewer", viewer.to_str().unwrap(),
            "--out", out.to_str().unwrap(),
            "--approve", &approve,
            // The one part of a self-minted grant that is not a tautology.
            "--grant-destination", grant_dir.to_str().unwrap(),
            // The CLI pins a 5 GB source before the boundary runs; the 300 s default would be tight.
            "--grant-ttl", "900",
            "--viewer-program", "Spatial IDE bundle viewer",
            "--viewer-copyright", "Copyright (C) 2026 the Spatial IDE contributors",
            "--viewer-license", "AGPL-3.0-or-later",
            "--viewer-notice", "NOTICE.txt",
            "--corresponding-source-url", "https://example.invalid/spatial-ide",
        ])
        .output()
        .expect("run publish-bundle");
    let ms = t.elapsed().as_secs_f64() * 1000.0;
    let mut text = String::from_utf8_lossy(&output.stdout).to_string();
    text.push_str(&String::from_utf8_lossy(&output.stderr));
    (output.status.success(), ms, text)
}

fn verify_bundle(bundle: &Path) -> (bool, f64, String) {
    let exe = example_beside_me("verify-bundle");
    let summary_path = bundle.parent().unwrap().join("verify-summary.json");
    let t = Instant::now();
    let out = std::process::Command::new(exe)
        .args([
            "--bundle", bundle.to_str().unwrap(),
            "--json", summary_path.to_str().unwrap(),
            "--quiet",
        ])
        .output()
        .expect("run verify-bundle");
    let ms = t.elapsed().as_secs_f64() * 1000.0;
    let summary = std::fs::read_to_string(&summary_path).unwrap_or_else(|_| "null".into());
    (out.status.success(), ms, summary)
}

/// Compare every partition of two bundles byte for byte, one at a time.
///
/// Streaming rather than whole-bundle: at ~5.7 GB each, holding both would need more memory than
/// this machine has, and a determinism check that could not run at scale would be the wrong tool
/// for the one measurement that is about scale.
fn compare_partitions(a: &Path, b: &Path) -> (usize, bool, Option<String>) {
    let da = a.join("data");
    let db = b.join("data");
    let mut names: Vec<String> = match std::fs::read_dir(&da) {
        Ok(rd) => rd
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().to_string())
            .collect(),
        Err(e) => return (0, false, Some(format!("bundle A has no data directory: {e}"))),
    };
    names.sort();

    let mut compared = 0usize;
    for name in &names {
        let pa = match std::fs::read(da.join(name)) {
            Ok(v) => v,
            Err(e) => return (compared, false, Some(format!("{name}: unreadable in A ({e})"))),
        };
        let pb = match std::fs::read(db.join(name)) {
            Ok(v) => v,
            Err(e) => return (compared, false, Some(format!("{name}: absent from B ({e})"))),
        };
        if pa != pb {
            return (compared, false, Some(format!("{name}: bytes differ")));
        }
        compared += 1;
    }
    (compared, true, None)
}

/// A built binary beside this test binary.
///
/// Derived rather than taken from `CARGO_BIN_EXE_*`, and asserted to exist — the alternative is a
/// harness that silently measures a stale binary, which is the failure `pin-tree.mjs --binaries`
/// exists to catch one level up.
fn binary_beside_me(name: &str) -> PathBuf {
    let me = std::env::current_exe().expect("the test binary knows where it is");
    let profile = me.parent().and_then(|d| d.parent()).expect("target/<profile>/deps/<test>");
    let exe = if cfg!(windows) { format!("{name}.exe") } else { name.to_string() };
    let path = profile.join(&exe);
    assert!(path.exists(), "{name} is not built at {}", path.display());
    path
}

fn example_beside_me(name: &str) -> PathBuf {
    let me = std::env::current_exe().expect("the test binary knows where it is");
    let profile = me.parent().and_then(|d| d.parent()).expect("target/<profile>/deps/<test>");
    let exe = if cfg!(windows) { format!("{name}.exe") } else { name.to_string() };
    let path = profile.join("examples").join(&exe);
    assert!(path.exists(), "the {name} example is not built at {}", path.display());
    path
}
