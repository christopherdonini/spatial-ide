//! **The 5 GB scale pass**, as a committed, re-runnable harness.
//!
//! ```bash
//! cargo test --release -p spatial-kernel --test scale_pass -- --ignored --nocapture
//! ```
//!
//! `#[ignore]`d: it generates ~5 GB, publishes ~5.7 GB twice, and runs for the better part of an
//! hour. It refuses to run on a debug build.
//!
//! **Everything it does is pre-registered in `kernel/SCALE-PASS-PREREGISTRATION.md`**, which was
//! committed before this file existed and before the fixture existed. Where a number appears here
//! it is because that file declared it; where a ceiling appears here it is because that file
//! declared it. Changing either after a result has been seen invalidates the run.
//!
//! ## The cold-open row is not here
//!
//! It needs three reboots and an operator. `kernel/scripts/cold-open.ps1` is that phase, and it runs
//! **after** everything in this file — decided with the human before any measurement, because a
//! reboot re-evicts the cache anyway and an operator's window should not be spent on a pass that
//! might invalidate earlier.
//!
//! ## What this harness may and may not be used for
//!
//! - **Every comparison is within-session.** The canary is taken at each phase boundary; a spread
//!   beyond the declared 10 % invalidates that phase.
//! - **No throughput claim.** Bytes and durations are recorded side by side and never divided.
//! - **Nothing here is compared with any earlier section of `kernel/RESULTS.md`.** This fixture has
//!   403 row groups where every earlier one had a single row group, and the confound is declared.
//! - The 145 MB **in-session control** is generated by this same binary in this same session, with
//!   the same `row_group_rows`, and it is the only thing the 5 GB memory figure may be compared
//!   with.

