fn evidence_dir() -> PathBuf {
    let d = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("target/slice-evidence/scale-pass");
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn fixture_path() -> PathBuf {
    evidence_dir().join("parcels-5gb.parquet")
}

fn control_path() -> PathBuf {
    evidence_dir().join("parcels-control-145mb.parquet")
}

fn spec_5gb() -> FixtureSpec {
    FixtureSpec {
        features: FEATURES,
        avg_vertices: AVG_VERTICES,
        hole_every: HOLE_EVERY,
        seed: SEED,
        crs_mode: CrsMode::DeclaredLv95,
        with_covering_bbox: true,
        chunk: CHUNK,
        row_group_rows: ROW_GROUP_ROWS,
        identity: IdentityMode::NativeUnique,
        attributes: AttributeMode::None,
        // Determinism-critical: a source-declared license needs no `--license-at`, and an
        // operator-declared instant is a semantic input inside ADR-017 §12's determinism surface.
        license: LicenseMode::DeclaredBySource,
    }
}

fn spec_control() -> FixtureSpec {
    FixtureSpec { features: CONTROL_FEATURES, ..spec_5gb() }
}

/// Progress that feeds the watchdog's silence clock and counts chunks.
struct GenProgress<'a> {
    dog: &'a Watchdog,
    chunks: AtomicUsize,
}

impl FixtureProgress for GenProgress<'_> {
    fn chunk_written(&self, _i: usize, written: usize, total: usize, bytes: u64) {
        self.dog.beat();
        let n = self.chunks.fetch_add(1, Ordering::Relaxed);
        if n % 50 == 0 {
            println!("  [generate] {written}/{total} features, {bytes} B");
        }
    }
}

/// SHA-256 of a file, streamed. **Never called at cold time** — see the preregistration §4a.
fn sha256_file(path: &Path) -> std::io::Result<String> {
    use std::io::Read as _;
    let mut f = std::fs::File::open(path)?;
    let mut buf = vec![0u8; 8 << 20];
    let mut all: Vec<u8> = Vec::new();
    // Hashed incrementally would be better; `canonical::sha256_hex` takes a slice, so this reads in
    // blocks and accumulates. At 5 GB that is 5 GB resident for the duration of the hash — which is
    // why this is called in its own phase, never inside a memory measurement.
    loop {
        let n = f.read(&mut buf)?;
        if n == 0 {
            break;
        }
        all.extend_from_slice(&buf[..n]);
    }
    Ok(spatial_renderer::canonical::sha256_hex(&all))
}

/// One streaming run: time to first batch, total time, rows, batches.
struct StreamRun {
    first_batch_ms: f64,
    total_ms: f64,
    rows: u64,
    batches: usize,
}

fn stream_once(ds: &Dataset, q: &ViewportQuery, dog: &Watchdog) -> StreamRun {
    let cancel = CancelToken::new();
    let t0 = Instant::now();
    let mut stream = ds.stream_with_cancel(q, cancel).expect("stream opens");
    let mut payload = Vec::new();
    let mut first: Option<f64> = None;
    let mut rows = 0u64;
    let mut batches = 0usize;

    while let Some(info) = stream.next_into(&mut payload) {
        let info = info.expect("batch");
        if first.is_none() {
            first = Some(t0.elapsed().as_secs_f64() * 1000.0);
        }
        rows += info.rows as u64;
        batches += 1;
        payload.clear();
        dog.beat();
    }
    StreamRun {
        first_batch_ms: first.unwrap_or(f64::NAN),
        total_ms: t0.elapsed().as_secs_f64() * 1000.0,
        rows,
        batches,
    }
}

#[ignore = "measurement harness: ~5 GB of disk, tens of minutes, release-only"]
#[test]
fn measure_the_five_gigabyte_scale_pass() {
    refuse_debug("the 5 GB scale pass");

    let dir = evidence_dir();
    let mut json = String::from("{\n");
    let mut canaries: Vec<Canary> = Vec::new();

    let hardware = json_escape(&hardware_profile());
    let media = json_escape(&media_type());
    println!("hardware: {hardware}");
    println!("media:    {media}");
    json.push_str(&format!("  \"hardware\": \"{hardware}\",\n  \"media_type\": \"{media}\",\n"));
    json.push_str(&format!(
        "  \"preregistration\": \"kernel/SCALE-PASS-PREREGISTRATION.md\",\n  \"cadence_short_ms\": {CADENCE_SHORT_MS},\n  \"cadence_long_ms\": {CADENCE_LONG_MS},\n"
    ));

    canaries.push(Canary::take("start"));

    // ---- Phase 1: the fixtures -----------------------------------------------------------------
    let free_before = require_disk("generate");
    json.push_str(&format!("  \"free_bytes_before\": {free_before},\n"));

    let (facts, gen_ms) = generate(&fixture_path(), &spec_5gb(), CEIL_GENERATE, "generate-5gb");
    let (control_facts, control_gen_ms) = generate(
        &control_path(),
        &spec_control(),
        CEIL_GENERATE_CONTROL,
        "generate-control",
    );

    // **Predictions asserted, not recomputed.** A mismatch here is an instrument failure and stops
    // the pass; it is not a machine fact to be reported as a result.
    assert_eq!(facts.features, FEATURES, "the generator wrote a different feature count");
    assert_eq!(facts.rings, PREDICTED_RINGS, "ring count differs from the pre-registered prediction");
    assert!(
        (4.0e9..=6.5e9).contains(&(facts.bytes as f64)),
        "fixture is {} B, outside the pre-registered 4.0–6.5 GB regeneration band",
        facts.bytes
    );

    let fixture_sha = sha256_file(&fixture_path()).expect("hash the fixture");
    println!("fixture sha256: {fixture_sha}");

    json.push_str(&format!(
        "  \"fixture\": {{\"path\": \"parcels-5gb.parquet\", \"sha256\": \"{fixture_sha}\", \
         \"features\": {}, \"vertices\": {}, \"rings\": {}, \"bytes\": {}, \
         \"min_vertices\": {}, \"max_vertices\": {}, \"coord_bits_xor\": \"{:#018x}\", \
         \"extent\": [{:.3}, {:.3}, {:.3}, {:.3}], \"wall_ms\": {:.1}, \
         \"predicted_vertices\": 345414000, \"predicted_rings\": {PREDICTED_RINGS}, \
         \"predicted_bytes\": 5009600000, \"predicted_row_groups\": {PREDICTED_ROW_GROUPS}}},\n",
        facts.features, facts.vertices, facts.rings, facts.bytes,
        facts.min_vertices_per_feature, facts.max_vertices_per_feature, facts.coord_bits_xor,
        facts.extent[0], facts.extent[1], facts.extent[2], facts.extent[3], gen_ms
    ));
    json.push_str(&format!(
        "  \"control_fixture\": {{\"features\": {}, \"vertices\": {}, \"bytes\": {}, \"wall_ms\": {:.1}}},\n",
        control_facts.features, control_facts.vertices, control_facts.bytes, control_gen_ms
    ));
    canaries.push(Canary::take("after-generate"));

    // ---- Phase 2: warm open, and the identity scan isolated by A/B ------------------------------
    require_disk("open");
    let (open_full_ms, open_prelude_ms) = open_ab(&fixture_path());
    let scan_ms = open_full_ms - open_prelude_ms;
    println!(
        "open: full {open_full_ms:.1} ms | prelude-only {open_prelude_ms:.1} ms | scan {scan_ms:.1} ms"
    );
    json.push_str(&format!(
        "  \"warm_open\": {{\"full_ms\": {open_full_ms:.3}, \"prelude_only_ms\": {open_prelude_ms:.3}, \
         \"identity_scan_ms\": {scan_ms:.3}, \"basis\": \"A/B on two product paths \
         (skip_uniqueness_check true/false), same session, same binary\"}},\n"
    ));
    canaries.push(Canary::take("after-open"));

    // ---- Phase 3: streaming ---------------------------------------------------------------------
    require_disk("stream");
    let ds = Dataset::open(fixture_path()).expect("open the 5 GB fixture");

    let whole = ViewportQuery { bbox: None, bbox_crs: None, limit: None };
    let (whole_first, whole_total, whole_rows, whole_batches, whole_mem) =
        stream_phase(&ds, &whole, WHOLE_FILE_RUNS, CEIL_WHOLE_FILE, "whole-file");
    assert_eq!(whole_rows, FEATURES as u64, "the whole-file stream did not return every row");

    let e_lo = spatial_engine::fixture::E_LO;
    let n_lo = spatial_engine::fixture::N_LO;
    let quarter = ViewportQuery {
        bbox: Some(Bbox {
            xmin: e_lo,
            ymin: n_lo,
            xmax: e_lo + GRID_COLS / 2.0 * CELL_M,
            ymax: n_lo + GRID_COLS / 2.0 * CELL_M,
        }),
        bbox_crs: None,
        limit: None,
    };
    let (q_first, q_total, q_rows, q_batches, _) =
        stream_phase(&ds, &quarter, VIEWPORT_RUNS, CEIL_VIEWPORT, "quarter");

    let sixty_fourth = ViewportQuery {
        bbox: Some(Bbox {
            xmin: e_lo,
            ymin: n_lo,
            xmax: e_lo + GRID_COLS / 8.0 * CELL_M,
            ymax: n_lo + GRID_COLS / 8.0 * CELL_M,
        }),
        bbox_crs: None,
        limit: None,
    };
    let (s_first, s_total, s_rows, s_batches, _) =
        stream_phase(&ds, &sixty_fourth, VIEWPORT_RUNS, CEIL_VIEWPORT, "sixty-fourth");

    // **The strongest instrument check in the pass.** These are pure arithmetic over the
    // generator's grid; a mismatch means the filter or the generator is wrong, not that the
    // machine drifted. Recorded rather than asserted, because the covering-bbox filter is
    // conservative by design (it selects candidates whose bbox intersects), so the exact identity
    // is a prediction about the *grid*, and any difference is a finding worth reporting in full.
    println!("quarter rows {q_rows} (predicted {QUARTER_ROWS}); 1/64 rows {s_rows} (predicted {SIXTY_FOURTH_ROWS})");

    json.push_str(&format!(
        "  \"streaming\": {{\
         \"whole_file\": {{\"first_batch\": {}, \"total\": {}, \"rows\": {whole_rows}, \"batches\": {whole_batches}}},\
         \"quarter\": {{\"first_batch\": {}, \"total\": {}, \"rows\": {q_rows}, \"predicted_rows\": {QUARTER_ROWS}, \"batches\": {q_batches}}},\
         \"sixty_fourth\": {{\"first_batch\": {}, \"total\": {}, \"rows\": {s_rows}, \"predicted_rows\": {SIXTY_FOURTH_ROWS}, \"batches\": {s_batches}}}}},\n",
        summarize("whole-file first batch", &whole_first),
        summarize("whole-file total", &whole_total),
        summarize("quarter first batch", &q_first),
        summarize("quarter total", &q_total),
        summarize("1/64 first batch", &s_first),
        summarize("1/64 total", &s_total),
    ));
    canaries.push(Canary::take("after-streaming"));

    // ---- Phase 4: the memory row, with its in-session control -----------------------------------
    let control_ds = Dataset::open(control_path()).expect("open the control fixture");
    let (_, _, _, _, control_mem) =
        stream_phase(&control_ds, &whole, 1, CEIL_WHOLE_FILE, "control-whole-file");

    let peak_5gb = whole_mem.iter().copied().max().unwrap_or(0);
    let peak_control = control_mem.iter().copied().max().unwrap_or(0);
    println!("private commit peak: 5 GB {peak_5gb} B | 145 MB control {peak_control} B");
    json.push_str(&format!(
        "  \"memory\": {{\"peak_private_commit_5gb\": {peak_5gb}, \
         \"peak_private_commit_control\": {peak_control}, \
         \"declared_composed_bound_bytes\": 83886080, \
         \"caveat\": \"process private commit is NOT the bounded quantity. DuckDB's own streaming \
         buffer sits outside every declared bound by design. The bounded claim is the data-plane \
         window; these two figures are the two points the flatness statement needs, same session, \
         same binary.\"}},\n"
    ));
    canaries.push(Canary::take("after-memory"));

    // ---- Phase 5: cancellation mid-stream at scale ----------------------------------------------
    require_disk("cancel");
    let cancel_samples = cancel_phase(&ds, &whole);
    let cs = sorted(&cancel_samples);
    let cancel_max = cs.last().copied().unwrap_or(f64::NAN);
    println!(
        "cancellation: n={} p50 {:.2} ms p95 {:.2} ms max {:.2} ms (budget {CANCEL_BUDGET_MS} ms)",
        cs.len(),
        pct(&cs, 0.5),
        pct(&cs, 0.95),
        cancel_max
    );
    json.push_str(&format!(
        "  \"cancellation_mid_stream\": {{\"summary\": {}, \"budget_ms\": {CANCEL_BUDGET_MS}, \"max_ms\": {cancel_max:.3}}},\n",
        summarize("cancel mid-stream at 5 GB", &cancel_samples)
    ));
    canaries.push(Canary::take("after-cancel"));

    // ---- Close out -------------------------------------------------------------------------------
    let (spread, canary_ok) = canary_spread(&canaries);
    let free_after = free_bytes_on_c().unwrap_or(0);
    let points: Vec<String> = canaries.iter().map(Canary::json).collect();
    json.push_str(&format!(
        "  \"canary\": {{\"points\": [{}], \"long_min_spread\": {spread:.4}, \"declared_max_spread\": {CANARY_MAX_SPREAD}, \"within_declared\": {canary_ok}}},\n",
        points.join(", ")
    ));
    json.push_str(&format!("  \"free_bytes_after\": {free_after},\n"));
    json.push_str("  \"note\": \"Publish, determinism and strict-reader phases are driven by kernel/scripts/run-scale-publish.mjs against the same frozen binaries; the cold-open row is kernel/scripts/cold-open.ps1 and runs last.\"\n}\n");

    let artifact = dir.join("scale-pass.json");
    std::fs::write(&artifact, &json).expect("write the evidence artifact");
    println!("artifact: {}", artifact.display());

    // **Asserted last, so the artifact exists either way.** A phase whose canary moved is recorded
    // with its invalidator named rather than silently dropped.
    assert!(
        canary_ok,
        "canary spread {spread:.4} exceeds the declared {CANARY_MAX_SPREAD} — the machine moved \
         underneath these numbers and the run is invalidated"
    );
}

/// Generate one fixture under a declared ceiling, returning its facts and wall time.
fn generate(
    path: &Path,
    spec: &FixtureSpec,
    ceiling: Duration,
    phase: &'static str,
) -> (FixtureFacts, f64) {
    // **Refused rather than reused, and the reason is not tidiness.** `FixtureFacts` are what the
    // *writer* measured while writing — vertices, rings, the coordinate XOR, the extent — and none
    // of them can be recovered from a finished file without re-reading and re-deriving them, which
    // would be a second implementation of the generator's own accounting. A reuse path would have
    // to fabricate the facts this pass records beside its predictions.
    assert!(
        !path.exists(),
        "{} already exists. This pass generates once and records the facts from that generation. \
         Remove the file to re-run the phase — deliberately manual, because it is 5 GB.",
        path.display()
    );

    let cancel = CancelToken::new();
    let dog = Watchdog::start(phase, ceiling, Some(SILENCE_GENERATE), cancel.clone());
    let progress = GenProgress { dog: &dog, chunks: AtomicUsize::new(0) };

    let t0 = Instant::now();
    let facts = write_geoparquet_cancellable(path, spec, &cancel, Some(&progress))
        .expect("fixture generation");
    let ms = t0.elapsed().as_secs_f64() * 1000.0;
    let fired = dog.finish();
    assert!(!fired, "the {phase} watchdog fired; this phase is unmeasured and is not re-run");

    // Wall time and bytes side by side, deliberately not divided.
    println!("[{phase}] {} features, {} B, {ms:.0} ms", facts.features, facts.bytes);
    (facts, ms)
}

/// Open the dataset twice on two product paths, so the identity scan is a *difference* rather than
/// an inference. Returns (full open ms, prelude-only ms).
fn open_ab(path: &Path) -> (f64, f64) {
    let cancel = CancelToken::new();
    let dog = Watchdog::start("open-ab", CEIL_OPEN, None, cancel);

    let t0 = Instant::now();
    let full = Dataset::open(path).expect("open with the uniqueness scan");
    let full_ms = t0.elapsed().as_secs_f64() * 1000.0;
    drop(full);

    let mut declared = IdentityDeclaration::new("id", "scale-pass", "2026-08-07T00:00:00Z");
    declared.skip_uniqueness_check = true;
    let t1 = Instant::now();
    let prelude = Dataset::open_with_declared_identity(path, declared, &CancelToken::new())
        .expect("open with the scan skipped");
    let prelude_ms = t1.elapsed().as_secs_f64() * 1000.0;
    drop(prelude);

    assert!(!dog.finish(), "the open watchdog fired; this phase is unmeasured");
    (full_ms, prelude_ms)
}

/// n runs of one query, under a declared ceiling, with private commit sampled throughout.
#[allow(clippy::type_complexity)]
fn stream_phase(
    ds: &Dataset,
    q: &ViewportQuery,
    runs: usize,
    ceiling: Duration,
    phase: &'static str,
) -> (Vec<f64>, Vec<f64>, u64, usize, Vec<usize>) {
    let cancel = CancelToken::new();
    let dog = Watchdog::start(phase, ceiling, Some(SILENCE_STREAM), cancel);
    let sampler = MemorySampler::start(CADENCE_LONG_MS);

    let mut first = Vec::with_capacity(runs);
    let mut total = Vec::with_capacity(runs);
    let (mut rows, mut batches) = (0u64, 0usize);

    for i in 0..runs {
        let r = stream_once(ds, q, &dog);
        println!(
            "  [{phase}] run {}/{runs}: first batch {:.1} ms, total {:.1} ms, {} rows, {} batches",
            i + 1,
            r.first_batch_ms,
            r.total_ms,
            r.rows,
            r.batches
        );
        first.push(r.first_batch_ms);
        total.push(r.total_ms);
        rows = r.rows;
        batches = r.batches;
    }

    let samples = sampler.finish();
    assert!(!dog.finish(), "the {phase} watchdog fired; this phase is unmeasured and is not re-run");
    (first, total, rows, batches, samples)
}

/// Cancellation mid-stream, producer-observed, in one process so both observations share a clock.
fn cancel_phase(ds: &Dataset, q: &ViewportQuery) -> Vec<f64> {
    let mut samples = Vec::with_capacity(CANCEL_TRIALS);

    for trial in 0..CANCEL_TRIALS {
        let cancel = CancelToken::new();
        let dog = Watchdog::start("cancel", CEIL_CANCEL, None, cancel.clone());
        let sampler = MemorySampler::start(CADENCE_SHORT_MS);

        let mut stream = ds.stream_with_cancel(q, cancel.clone()).expect("stream opens");
        let mut payload = Vec::new();

        // Let the stream reach steady state before cancelling — a cancel issued before the first
        // batch measures a different thing, and that case has its own coverage in the ordinary
        // suite. Two batches is enough at this size and keeps the trial short.
        let mut seen = 0;
        while seen < 2 {
            match stream.next_into(&mut payload) {
                Some(Ok(_)) => {
                    seen += 1;
                    payload.clear();
                }
                Some(Err(e)) => panic!("stream failed before cancellation: {e}"),
                None => break,
            }
        }

        let t = Instant::now();
        cancel.cancel();
        // Producer-observed acknowledgement: drain until the stream reports it is over.
        while let Some(r) = stream.next_into(&mut payload) {
            payload.clear();
            if r.is_err() {
                break;
            }
        }
        let ms = t.elapsed().as_secs_f64() * 1000.0;
        samples.push(ms);
        println!("  [cancel] trial {}/{CANCEL_TRIALS}: {ms:.2} ms", trial + 1);

        let _ = sampler.finish();
        assert!(!dog.finish(), "the cancel watchdog fired on trial {trial}");
    }
    samples
}

